/**
 * Copies the front-end dependencies from node_modules to js/vendor and css/vendor,
 * and builds a Lucide bundle holding only the icons the site uses.
 * Run by the Dockerfile, or locally with `npm run vendor`.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const mod = (p) => path.join(ROOT, "node_modules", p);
const out = (p) => path.join(ROOT, p);

function copy(from, to) {
    fs.mkdirSync(path.dirname(out(to)), { recursive: true });
    fs.cpSync(mod(from), out(to), { recursive: true });
}

// 1. Libraries
copy("leaflet/dist/leaflet.js", "js/vendor/leaflet.js");
copy("leaflet/dist/leaflet.css", "css/vendor/leaflet/leaflet.css");
copy("leaflet/dist/images", "css/vendor/leaflet/images");
copy("aos/dist/aos.js", "js/vendor/aos.js");
copy("aos/dist/aos.css", "css/vendor/aos.css");
copy("flatpickr/dist/flatpickr.min.js", "js/vendor/flatpickr.js");
copy("flatpickr/dist/l10n/fr.js", "js/vendor/flatpickr-fr.js");
copy("flatpickr/dist/flatpickr.min.css", "css/vendor/flatpickr.css");

// 2. Fonts (latin subset), declared in css/themes/fonts-*.css
[
    "@fontsource-variable/fraunces/files/fraunces-latin-opsz-normal.woff2",
    "@fontsource-variable/inter/files/inter-latin-wght-normal.woff2",
    "@fontsource-variable/playfair-display/files/playfair-display-latin-wght-normal.woff2",
    "@fontsource-variable/playfair-display/files/playfair-display-latin-wght-italic.woff2",
    "@fontsource/lato/files/lato-latin-300-normal.woff2",
    "@fontsource/lato/files/lato-latin-400-normal.woff2",
    "@fontsource/lato/files/lato-latin-700-normal.woff2",
].forEach((file) => copy(file, `css/vendor/fonts/${path.basename(file)}`));

// 3. Lucide: the full library is ~380 KB, the site uses a few dozen icons.
// Icons written in the code (data-lucide="…") are found automatically. Icons picked in the CMS
// (house_features.icon) or computed (amenityIcon in js/themes/pavillons/helpers.js) are listed here.
const EXTRA_ICONS = [
    // amenityIcon()
    "users", "waves", "bath", "bed-double", "wifi", "chef-hat", "sun", "car", "snowflake", "check",
    // Choices offered for house_features.icon
    "home", "house", "sofa", "armchair", "bed", "bed-single", "baby", "droplet", "shower-head", "toilet",
    "flower", "flower-2", "trees", "tree-pine", "leaf", "sprout", "fence", "tent", "umbrella", "sunset",
    "utensils", "utensils-crossed", "coffee", "wine", "microwave", "refrigerator", "washing-machine", "flame",
    "tv", "monitor", "laptop", "gamepad-2", "book-open", "music", "lamp", "key", "door-open", "warehouse",
    "bike", "sailboat", "ship", "anchor", "fish", "map", "map-pin", "compass", "mountain", "dog", "cat",
    "cigarette-off", "accessibility", "thermometer", "fan", "heater", "wind", "shirt", "dumbbell", "star",
    "heart", "camera", "image", "info", "phone", "mail", "calendar", "clock", "parking-meter", "plug",
];

const lucide = require(mod("lucide"));
const toPascal = (name) => name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

function scan(dir, names) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            if (entry.name !== "vendor") scan(full, names);
        } else if (entry.name.endsWith(".js")) {
            for (const [, name] of fs.readFileSync(full, "utf8").matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(name);
        }
    }
    return names;
}

const names = scan(out("js"), new Set(EXTRA_ICONS));
const icons = {};
const missing = [];
for (const name of [...names].sort()) {
    const node = lucide.icons[toPascal(name)];
    if (node) icons[name] = node;
    else missing.push(name);
}
if (missing.length) console.warn(`⚠️ Unknown Lucide icons: ${missing.join(", ")}`);

const bundle = `/* Lucide ${require(mod("lucide/package.json")).version} (ISC license), ${Object.keys(icons).length} icons. Generated by scripts/vendor.js: do not edit. */
(function () {
    var ICONS = ${JSON.stringify(icons)};
    var DEFAULTS = { xmlns: "http://www.w3.org/2000/svg", width: 24, height: 24, viewBox: "0 0 24 24", fill: "none", stroke: "currentColor", "stroke-width": 2, "stroke-linecap": "round", "stroke-linejoin": "round" };
    var SVG_NS = "http://www.w3.org/2000/svg";

    function createNode(tag, attrs) {
        var el = document.createElementNS(SVG_NS, tag);
        Object.keys(attrs).forEach(function (key) { el.setAttribute(key, String(attrs[key])); });
        return el;
    }

    // Same output as lucide.createIcons(): <i data-lucide="x" class="…"> becomes <svg class="lucide lucide-x …">
    function createIcons(options) {
        var root = (options && options.root) || document;
        root.querySelectorAll("[data-lucide]").forEach(function (element) {
            var name = element.getAttribute("data-lucide");
            var node = ICONS[name];
            if (!node) return console.warn("Lucide icon \\"" + name + "\\" is not bundled: add it to EXTRA_ICONS in scripts/vendor.js");
            var attrs = Object.assign({}, DEFAULTS);
            Array.prototype.forEach.call(element.attributes, function (attr) { attrs[attr.name] = attr.value; });
            attrs["class"] = ["lucide", "lucide-" + name, element.getAttribute("class") || ""].join(" ").trim();
            var svg = createNode("svg", attrs);
            node.forEach(function (child) { svg.appendChild(createNode(child[0], child[1])); });
            if (element.parentNode) element.parentNode.replaceChild(svg, element);
        });
    }

    window.lucide = { createIcons: createIcons };
})();
`;
fs.writeFileSync(out("js/vendor/lucide.js"), bundle);

console.log(`✅ Vendor files copied, Lucide bundle: ${Object.keys(icons).length} icons, ${(bundle.length / 1024).toFixed(1)} KB`);
